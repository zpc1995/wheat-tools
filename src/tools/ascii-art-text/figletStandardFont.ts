/**
 * The built-in FIGlet font: Glenn Chappell's `standard` face, ASCII 32-126.
 *
 * ## Why this data lives in the repository instead of a dependency
 *
 * The tool renders ASCII art itself rather than depending on `figlet`, whose
 * package is mostly a directory of ~150 font files; pulling it in for a single
 * face would add far more weight than the 95 glyphs below.
 *
 * ## Provenance
 *
 * Extracted verbatim from `fonts/Standard.flf` in patorjk/figlet.js, which is
 * the classic FIGlet "standard" font by Glenn Chappell and Ian Chai (1993).
 * `scripts/check-ascii-art-text.mjs` carries its own copy of the same upstream
 * glyph block and re-parses it independently, so a corrupted or edited glyph is
 * caught rather than silently shipped.
 *
 * ## Shape of the data
 *
 * Rows are stored **right-trimmed** and the column width is stored separately.
 * FIGlet itself keeps the padding inside each line, and the hardblank character
 * (FIGlet's blank that survives smushing) appears inside those padded columns.
 * Keeping the padding in the source file was rejected on purpose: trailing
 * whitespace is invisible, survives review, and any editor or formatter that
 * strips it would silently break the artwork. Widths are restored at render
 * time by `glyphRows()`, which reproduces the padded rows exactly.
 */

